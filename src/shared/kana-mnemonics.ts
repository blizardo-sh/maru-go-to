export const kanaMnemonics = Object.fromEntries(hints.flatMap(([glyph, title, hint, kataTitle, kataHint], index) => [
 [glyph, { glyph, title, hint, atlas: `hiragana-${Math.floor(index / 24) + 1}`, cell: index % 24 }],
 [katakana(glyph), { glyph: katakana(glyph), title: kataTitle, hint: kataHint, atlas: `katakana-${Math.floor(index / 24) + 1}`, cell: index % 24 }],
])) as Record<string, { glyph: string; title: string; hint: string; atlas: string; cell: number }>;

export function kanaMnemonic(glyph: string) {
 const base = glyph.normalize('NFD')[0]?.normalize('NFC') ?? glyph;
 const entry = kanaMnemonics[glyph] ?? kanaMnemonics[base];
 return entry ? { ...entry, hint: entry.hint + (glyph !== entry.glyph ? (glyph.length>1&&glyph.normalize('NFD')[1]!=='゙'&&glyph.normalize('NFD')[1]!=='゚'?' Маленький знак справа образует слитный звук с базовым знаком.':' Дакутэн (две черты) или хандакутэн (кружок) меняет звук базового знака.') : '') } : undefined;
}

// Measured whitespace between generated rows; the first sheet is not an exact grid.
export function kanaMnemonicFrame(entry: {atlas: string; cell: number}) {
 const rows = entry.atlas === 'hiragana-1' ? [0,267,519,761,1024] : [0,256,512,768,1024];
 const row = Math.floor(entry.cell / 6);
 return { x: entry.cell % 6 * 256, y: rows[row]!, width: 256, height: rows[row+1]! - rows[row]! };
}
